PRAGMA foreign_keys = ON;

CREATE TABLE STATUS (id INTEGER PRIMARY KEY, nome TEXT NOT NULL UNIQUE);
CREATE TABLE PERFIL (id INTEGER PRIMARY KEY, nome TEXT NOT NULL UNIQUE);
CREATE TABLE CLINICA (
  id INTEGER PRIMARY KEY, nome TEXT NOT NULL, cnpj TEXT, email TEXT, telefone TEXT, endereco TEXT,
  status INTEGER REFERENCES STATUS(id), dt_registro date, dt_atualizacao date
);
CREATE TABLE USUARIO (
  id INTEGER PRIMARY KEY, nome TEXT NOT NULL, email TEXT NOT NULL UNIQUE COLLATE NOCASE,
  senha TEXT NOT NULL, perfil INTEGER REFERENCES PERFIL(id), dt_ult_acesso date,
  dt_registro date, dt_atualizacao date
);
CREATE TABLE USUARIO_CLINICA (
  id INTEGER PRIMARY KEY, usuario_id INTEGER NOT NULL REFERENCES USUARIO(id),
  perfil_id INTEGER NOT NULL REFERENCES PERFIL(id), clinica_id INTEGER NOT NULL REFERENCES CLINICA(id),
  status INTEGER NOT NULL REFERENCES STATUS(id), UNIQUE(usuario_id, clinica_id)
);
CREATE TABLE PACIENTE (
  id INTEGER PRIMARY KEY, usuario_id INTEGER NOT NULL UNIQUE REFERENCES USUARIO(id),
  clinica_id INTEGER NOT NULL REFERENCES CLINICA(id), cpf TEXT, dt_nasc date, telefone TEXT,
  sexo TEXT, endereco TEXT, Signo TEXT
);
CREATE TABLE TERAPEUTA (
  id INTEGER PRIMARY KEY, usuario_id INTEGER NOT NULL UNIQUE REFERENCES USUARIO(id),
  cpf TEXT, registro_prof TEXT, formacao TEXT
);
CREATE TABLE TERAPEUTA_DISPONIBILIDADE (
  id INTEGER PRIMARY KEY, usuario_id INTEGER NOT NULL REFERENCES USUARIO(id),
  clinica_id INTEGER NOT NULL REFERENCES CLINICA(id), dia_semana INTEGER NOT NULL CHECK(dia_semana BETWEEN 0 AND 6),
  hr_ini TIME NOT NULL, hr_fim TIME NOT NULL, CHECK(hr_ini < hr_fim)
);
CREATE TABLE ESPECIALIDADE (id INTEGER PRIMARY KEY, nome TEXT NOT NULL, descricao TEXT, status INTEGER REFERENCES STATUS(id));
CREATE TABLE TERAPEUTA_ESPECIALIDADE (
  id INTEGER PRIMARY KEY, terapeuta_id INTEGER NOT NULL REFERENCES TERAPEUTA(id),
  especialidade_id INTEGER NOT NULL REFERENCES ESPECIALIDADE(id), clinica_id INTEGER NOT NULL REFERENCES CLINICA(id),
  UNIQUE(terapeuta_id, especialidade_id, clinica_id)
);
CREATE TABLE TERAPIA (
  id INTEGER PRIMARY KEY, especialidade_id INTEGER NOT NULL REFERENCES ESPECIALIDADE(id),
  nome TEXT NOT NULL, descricao TEXT, duracao_min INTEGER NOT NULL, status INTEGER REFERENCES STATUS(id)
);
CREATE TABLE DIAGNOSTICO (
  id INTEGER PRIMARY KEY, terapeuta_id INTEGER NOT NULL REFERENCES TERAPEUTA(id),
  paciente_id INTEGER NOT NULL REFERENCES PACIENTE(id), descricao TEXT NOT NULL, dt_diagnostico TEXT
);
CREATE TABLE PROTOCOLO (
  id INTEGER PRIMARY KEY, terapeuta_id INTEGER NOT NULL REFERENCES TERAPEUTA(id),
  diagnostico_id INTEGER REFERENCES DIAGNOSTICO(id), nome TEXT NOT NULL, Sintomas TEXT, objetivo TEXT
);
CREATE TABLE PROTOCOLO_ETAPA (
  id INTEGER PRIMARY KEY, protocolo_id INTEGER NOT NULL REFERENCES PROTOCOLO(id), sequencia INTEGER NOT NULL,
  terapia_id INTEGER NOT NULL REFERENCES TERAPIA(id), dt_inicio date, dt_fim date, descricao TEXT, obs TEXT,
  UNIQUE(protocolo_id, sequencia)
);
CREATE TABLE DIAGNOSTICO_PROTOCOLO (
  id INTEGER PRIMARY KEY, diagnostico_id INTEGER NOT NULL REFERENCES DIAGNOSTICO(id),
  protocolo_etapa_id INTEGER NOT NULL REFERENCES PROTOCOLO_ETAPA(id), dt_diagnostico date,
  status INTEGER REFERENCES STATUS(id)
);
CREATE TABLE EVOLUCAO (
  id INTEGER PRIMARY KEY, diagnostico_protocolo_id INTEGER NOT NULL REFERENCES DIAGNOSTICO_PROTOCOLO(id),
  descricao TEXT NOT NULL, dt_evolucao date, status INTEGER REFERENCES STATUS(id)
);
CREATE TABLE AGENDA (
  id INTEGER PRIMARY KEY, paciente_id INTEGER NOT NULL REFERENCES PACIENTE(id),
  terapeuta_id INTEGER NOT NULL REFERENCES TERAPEUTA(id), terapia_id INTEGER NOT NULL REFERENCES TERAPIA(id),
  dt_inicio date NOT NULL, dt_fim date NOT NULL, status INTEGER REFERENCES STATUS(id), CHECK(dt_inicio < dt_fim)
);
CREATE TABLE ATENDIMENTO (
  id INTEGER PRIMARY KEY, paciente_id INTEGER NOT NULL REFERENCES PACIENTE(id),
  terapeuta_id INTEGER NOT NULL REFERENCES TERAPEUTA(id), terapia_id INTEGER NOT NULL REFERENCES TERAPIA(id),
  dt_atend date NOT NULL, status INTEGER REFERENCES STATUS(id), dt_inicio_real TEXT,
  exames_solicitados INTEGER NOT NULL DEFAULT 0
);
CREATE TABLE PRONTUARIO (
  id INTEGER PRIMARY KEY, paciente_id INTEGER NOT NULL REFERENCES PACIENTE(id),
  atendimento_id INTEGER NOT NULL REFERENCES ATENDIMENTO(id), status INTEGER REFERENCES STATUS(id),
  UNIQUE(atendimento_id)
);
CREATE TABLE ANAMNESE (
  id INTEGER PRIMARY KEY, atendimento_id INTEGER NOT NULL REFERENCES ATENDIMENTO(id),
  descricao TEXT, dt_registro TEXT
);
CREATE TABLE PERGUNTAS (id INTEGER PRIMARY KEY, descricao TEXT NOT NULL);
CREATE TABLE ANAMNESE_PERGUNTAS (
  id INTEGER PRIMARY KEY, anamnese_id INTEGER NOT NULL REFERENCES ANAMNESE(id),
  pergunta_id INTEGER NOT NULL REFERENCES PERGUNTAS(id), Resposta TEXT
);
CREATE TABLE ANEXO (
  id INTEGER PRIMARY KEY, prontuario_id INTEGER NOT NULL REFERENCES PRONTUARIO(id),
  atendimento_id INTEGER NOT NULL REFERENCES ATENDIMENTO(id), arquivo TEXT, descricao TEXT, dt_atualizacao date
);
CREATE TABLE BIOWELL_AVALIACAO (
  id INTEGER PRIMARY KEY, prontuario_id INTEGER NOT NULL REFERENCES PRONTUARIO(id),
  atendimento_id INTEGER NOT NULL REFERENCES ATENDIMENTO(id), dt_avaliacao TEXT,
  indice_energetico REAL, indice_estresse REAL
);
CREATE TABLE RELATORIO (
  id INTEGER PRIMARY KEY, atendimento_id INTEGER NOT NULL REFERENCES ATENDIMENTO(id),
  tipo TEXT, arquivo_pdf TEXT, dt_geracao date
);
CREATE TABLE PAGAMENTO (
  id INTEGER PRIMARY KEY, agenda_id INTEGER REFERENCES AGENDA(id), atendimento_id INTEGER REFERENCES ATENDIMENTO(id),
  valor REAL, forma_pagamento TEXT, status INTEGER REFERENCES STATUS(id)
);

-- Session and notification records are the two technical tables explicitly retained by the owner.
CREATE TABLE sessions (
  token_hash TEXT PRIMARY KEY, user_id INTEGER NOT NULL REFERENCES USUARIO(id) ON DELETE CASCADE,
  clinic_id INTEGER NOT NULL REFERENCES CLINICA(id) ON DELETE CASCADE,
  user_clinic_id INTEGER NOT NULL REFERENCES USUARIO_CLINICA(id) ON DELETE CASCADE,
  patient_id INTEGER REFERENCES PACIENTE(id) ON DELETE CASCADE,
  therapist_id INTEGER REFERENCES TERAPEUTA(id) ON DELETE CASCADE,
  expires_at TEXT NOT NULL, created_at TEXT NOT NULL
);
CREATE TABLE notifications (
  id INTEGER PRIMARY KEY, clinic_id INTEGER NOT NULL REFERENCES CLINICA(id) ON DELETE CASCADE,
  user_id INTEGER REFERENCES USUARIO(id) ON DELETE SET NULL, recipient TEXT NOT NULL,
  channel TEXT NOT NULL CHECK(channel IN ('EMAIL','WHATSAPP')), event TEXT NOT NULL,
  status TEXT NOT NULL, details TEXT, created_at TEXT NOT NULL
);

CREATE INDEX usuario_clinica_user_idx ON USUARIO_CLINICA(usuario_id, status);
CREATE INDEX usuario_clinica_clinic_idx ON USUARIO_CLINICA(clinica_id, perfil_id, status);
CREATE INDEX agenda_therapist_datetime_idx ON AGENDA(terapeuta_id, dt_inicio, dt_fim);
CREATE INDEX agenda_patient_datetime_idx ON AGENDA(paciente_id, dt_inicio, dt_fim);
CREATE INDEX atendimento_patient_datetime_idx ON ATENDIMENTO(paciente_id, dt_atend);
CREATE INDEX notifications_clinic_idx ON notifications(clinic_id, status, created_at);

PRAGMA user_version = 1;
